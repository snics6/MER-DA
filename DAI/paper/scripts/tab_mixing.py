"""Table for Section 3 (gain of adding one source corpus, single-source setting).

Reads results/e76_analysis/e76a_1_kind.csv (E76 analysis, commit e39e54a) and writes
sections/tab_mixing.tex. Run from anywhere: python DAI/paper/scripts/tab_mixing.py
"""
import hashlib
import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "results/e76_analysis/e76a_1_kind.csv"
OUT = Path(__file__).resolve().parents[1] / "sections/tab_mixing.tex"

ORDER = ["A", "A(HuBERT)", "V", "T", "AV", "VT", "AT", "AVT"]  # project-wide order
LABEL = {"A": "A (WavLM)", "A(HuBERT)": "A (HuBERT)"}
KS = ["1", "5", "10", "25", "50", "all"]


def main() -> None:
    header = json.loads(SRC.open().readline().lstrip("# "))
    d = pd.read_csv(SRC, comment="#")
    d["K"] = d["K"].astype(str)
    sha = hashlib.sha256(SRC.read_bytes()).hexdigest()[:16]
    rows = []
    for s in ORDER:
        g = d[d.short == s].set_index("K")
        n_t, n_p = int(g.loc["1", "n_targets"]), int(g.loc["1", "n_pairs"])
        mean = " & ".join(f"${g.loc[k, 'mean_gain']:+.1f}$" for k in KS)
        ci = " & ".join(f"\\tiny$[{g.loc[k, 'lo']:+.1f}, {g.loc[k, 'hi']:+.1f}]$" for k in KS)
        rows.append(f"{LABEL.get(s, s)} & {n_t}/{n_p} & {mean} \\\\")
        rows.append(f" & & {ci} \\\\[2pt]")
    tex = [
        f"% Generated by DAI/paper/scripts/tab_mixing.py from {SRC.relative_to(ROOT)}",
        f"% source sha256[:16]={sha}; analysis commit={header['commit'][:7]}; B={header['B']}; seed={header['seed']}",
        "\\begin{table*}[t]",
        "\\caption{Gain of adding one source corpus in the single-source setting (UAR points, merged minus target-only).",
        "Each cell is the mean over the source--target pairs of a feature set, averaged over ten repetitions;",
        "the bracket is the 95\\% interval: the two-stage bootstrap over speakers and repetitions, joined with the leave-one-speaker-out jackknife $t$ interval when a target has fewer than 20 effective speakers (Section~\\ref{sec:stats}).",
        "$K$ is the number of labelled target utterances per emotion; ``all'' uses the whole labelled target training pool.",
        "Pair-level counts are given in the text.}",
        "\\label{tab:mixing}",
        "\\centering",
        "\\footnotesize",
        "\\setlength{\\tabcolsep}{3pt}",
        "\\begin{tabular}{@{}lc*{6}{c}@{}}",
        "\\toprule",
        "Feature set & Targets/pairs & $K=1$ & $5$ & $10$ & $25$ & $50$ & all \\\\",
        "\\midrule",
        *rows,
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table*}",
    ]
    OUT.write_text("\n".join(tex) + "\n")
    print(f"wrote {OUT} ({len(ORDER)} feature sets, sha {sha})")


if __name__ == "__main__":
    main()
